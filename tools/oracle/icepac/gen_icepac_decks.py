"""Generate the ICEPAC-mode oracle decks (Phase 3, task 18).

"ICEPAC" here is Prop-SL's ICEPAC mode run through voacapl: the stock
VOACAP engine with COEFFS URSI and FPROB 1.00 1.00 1.00 0.70 (sporadic E
on).  It is NOT the real ICEPAC program (ICED profile model, SSN + Q index,
the closed-source Icepacw.exe): voacapl contains no ICED code, its batch
driver's ``call icepac`` is commented out, and a Q index on the SUNSPOT card
lands in SUNSP(2), the second month's sunspot number, which a one-month deck
never reads.  So these decks validate cudacap against voacapl in that
mode, and against nothing ICED-based.

Card layouts are exactly tools/oracle/golden_decks/gen_matrix.py's (same
SYSTEM and ANTENNA cards); only COEFFS and FPROB differ.  Deck names follow
``<path>_m<MM>_s<SSN>_v<METHOD>[_long]_ice`` so tests/test_engine.py can
discover them in golden/dumps/luffy_icepac/ and read their CIRCUIT cards
from golden/p2p/icepac_decks/.

Writes golden/p2p/icepac_decks/<name>.dat and MANIFEST.tsv.  Capture with
tools/oracle/icepac/run_icepac_dumps.sh (via WSL).
"""

