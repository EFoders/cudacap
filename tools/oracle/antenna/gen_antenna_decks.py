"""Generate the antenna oracle decks (Phase 3, task 17).

Every deck in golden/p2p/matrix uses the sample.00 isotrope at both ends, so
the type-13 / type-14 FILE path through ANTCALC -- the MINFREQ..MAXFREQ row
range, the PARM(1) add, the type-13 azimuth interpolation at OFFAZIM, the
359 -> 0 azimuth wrap, the long-path azimuth flip -- had never been compared
against the Fortran.  These decks exercise exactly that, in the card format of
tools/oracle/golden_decks/gen_matrix.py (same SYSTEM / FPROB / METHOD cards),
with the ANTENNA cards varied.

ANTENNA card, decred.for:286-288 / antcalc.for:116-118:

    ANTENNA  itr idx minfreq maxfreq designfreq [file] beam power
    FORMAT(10x,4i5,f10.3,1x,a21,1x,f5.1,f10.4)

For the sample.00 isotrope (type 0) ANTCALC sets PARM(1) = designfreq, i.e.
the constant gain; on the RECEIVE card a non-zero power field replaces it
(antcalc.for:119).  For a file antenna designfreq is unused.

Writes golden/p2p/antenna_decks/<name>.dat and MANIFEST.tsv.  Capture with
    wsl bash tools/oracle/antenna/run_antenna_dumps.sh
(the LUFFY shim, tools/oracle/dumps/run_luffy_dumps.sh, pointed at these
decks and at golden/dumps/luffy_antenna).

The beam headings below were chosen against the path azimuth DAZEL0 gives at
each end (``voacap_gpu.scalar.dazel.dazel0``, ANTCALC's own routine) so that
OFFAZIM = path azimuth - beam lands where the deck name says; the expected
OFFAZIM is recorded in MANIFEST.tsv and asserted by the capture's _ant.csv.
"""

