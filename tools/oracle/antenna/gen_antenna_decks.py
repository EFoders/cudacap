def ant_card(itr, idx, fmin, fmax, design, path, beam, power):
    return (f"ANTENNA   {itr:5d}{idx:5d}{fmin:5d}{fmax:5d}{design:10.3f}"
            f"[{path:<21.21s}]{beam:5.1f}{power:10.4f}")


def deck(path_key, month, ssn, tx, rx, *, method=30, coeffs="CCIR", npsl=0,
         freqs=FREQ_BASE):
    """``tx`` / ``rx``: dict(file, beam, power[, design, fmin, fmax])."""
    t, tlat, tns, tlon, tew, r, rlat, rns, rlon, rew = PATHS[path_key]
    sl = "L" if npsl else "S"
    cards = []
    for itr, a in ((1, tx), (2, rx)):
        cards.append(ant_card(itr, itr, a.get("fmin", 2), a.get("fmax", 30),
                              a.get("design", 0.0), a["file"], a["beam"],
                              a["power"]))
    lines = [
        "COMMENT   generated by tools/oracle/antenna/gen_antenna_decks.py",
        "LINEMAX      55       number of lines-per-page",
        f"COEFFS    {coeffs}",
        "TIME          1   24    1    1",
        f"MONTH      1994{month:5.2f}",
        f"SUNSPOT   {ssn:4.0f}.",
        f"LABEL     {t:<20.20s}{r:<20.20s}",
        (f"CIRCUIT   {tlat:5.2f}{tns}{tlon:9.2f}{tew}{rlat:9.2f}{rns}"
         f"{rlon:9.2f}{rew}  {sl} {npsl:5d}"),
        "SYSTEM       1. 145. 0.10  90. 73.0 3.00 0.10",
        "FPROB      1.00 1.00 1.00 0.00",
        *cards,
        f"FREQUENCY {freqs}",
        f"METHOD    {method:5d}    0",
        "EXECUTE",
        "QUIT",
    ]
    return "\n".join(line.rstrip() for line in lines) + "\n"


