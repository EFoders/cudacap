"""Generate the tier-A golden-deck matrix (PLAN.md section 3A).

Deterministic sweep of P2P input decks over path geometry, season, solar
activity, coefficient set, and method, holding the system/antenna cards at
the test01 baseline.  Card layouts follow the reader formats in
reference/voacapl/src/voacapw/decred.for — notably CIRCUIT is
FORMAT(10X,F5.2,A1,3(F9.2,A1),4X,I5): the S/L letter in column 49 is
cosmetic; the trailing I5 (NPSL: 0 short, 1 long/through-antipode) is what
geom.for acts on.

Writes golden/p2p/matrix/decks/<name>.dat and MANIFEST.tsv.  Run the decks
through the oracle with:  wsl bash tools/oracle/golden_decks/run_matrix.sh
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = ROOT / "golden" / "p2p" / "matrix" / "decks"

# name: (tx label, tlat, NS, tlon, EW, rx label, rlat, NS, rlon, EW)
PATHS = {
    "lonpar": ("LONDON", 51.50, "N", 0.13, "W", "PARIS", 48.85, "N", 2.35, "E"),
    "tanbel": ("TANGIER, Morocco", 35.80, "N", 5.90, "W",
               "BELGRADE", 44.90, "N", 20.50, "E"),
    "latok": ("LOS ANGELES", 34.05, "N", 118.24, "W",
              "TOKYO", 35.68, "N", 139.77, "E"),
    "sydstg": ("SYDNEY", 33.87, "S", 151.21, "E",
               "SANTIAGO", 33.45, "S", 70.67, "W"),
    "fbahel": ("FAIRBANKS", 64.84, "N", 147.72, "W",
               "HELSINKI", 60.17, "N", 24.94, "E"),
    "toksyd": ("TOKYO", 35.68, "N", 139.77, "E",
               "SYDNEY", 33.87, "S", 151.21, "E"),
    "lonakl": ("LONDON", 51.50, "N", 0.13, "W",
               "AUCKLAND", 36.85, "S", 174.76, "E"),
}

FREQ_BASE = " 6.07 7.20 9.7011.8513.7015.3517.7321.6525.89 0.00 0.00"
FREQ_WIDE = " 2.50 3.50 5.00 7.0010.0014.0018.0021.0024.9029.90 0.00"


def deck(path_key, month, ssn, method=30, coeffs="CCIR", npsl=0,
         freqs=FREQ_BASE):
    tx, tlat, tns, tlon, tew, rx, rlat, rns, rlon, rew = PATHS[path_key]
    sl = "L" if npsl else "S"
    lines = [
        "COMMENT   generated by tools/oracle/golden_decks/gen_matrix.py",
        "LINEMAX      55       number of lines-per-page",
        f"COEFFS    {coeffs}",
        "TIME          1   24    1    1",
        f"MONTH      1994{month:5.2f}",
        f"SUNSPOT   {ssn:4.0f}.",
        f"LABEL     {tx:<20.20s}{rx:<20.20s}",
        (f"CIRCUIT   {tlat:5.2f}{tns}{tlon:9.2f}{tew}{rlat:9.2f}{rns}"
         f"{rlon:9.2f}{rew}  {sl} {npsl:5d}"),
        "SYSTEM       1. 145. 0.10  90. 73.0 3.00 0.10",
        "FPROB      1.00 1.00 1.00 0.00",
        "ANTENNA       1    1    2   30    10.000[samples/sample.00    ]"
        " 90.0  500.0000",
        "ANTENNA       2    2    2   30     0.000[samples/sample.00    ]"
        "270.0   20.0000",
        f"FREQUENCY {freqs}",
        f"METHOD    {method:5d}    0",
        "EXECUTE",
        "QUIT",
    ]
    return "\n".join(line.rstrip() for line in lines) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = []

    def emit(name, **kw):
        (OUT / f"{name}.dat").write_text(deck(**kw), newline="\n")
        manifest.append((name, kw))

    # Core: every path x season x activity level, method 30, CCIR
    for pk in PATHS:
        for month in (1, 4, 7, 10):
            for ssn in (15, 100, 160):
                emit(f"{pk}_m{month:02d}_s{ssn}_v30",
                     path_key=pk, month=month, ssn=ssn)
    # URSI coefficient variant
    for pk in ("tanbel", "toksyd"):
        emit(f"{pk}_m07_s100_v30_ursi",
             path_key=pk, month=7, ssn=100, coeffs="URSI")
    # Method 20 (system performance, no short/long smoothing)
    for pk in ("tanbel", "latok", "fbahel"):
        emit(f"{pk}_m01_s100_v20", path_key=pk, month=1, ssn=100, method=20)
    # Method 25 (all-modes table)
    emit("tanbel_m01_s100_v25", path_key="tanbel", month=1, ssn=100, method=25)
    # Method 9 (MUF-FOT table — early module 3 target)
    for pk in PATHS:
        emit(f"{pk}_m07_s100_v09", path_key=pk, month=7, ssn=100, method=9)
    # Long path (NPSL=1) on the near-antipodal circuit
    emit("lonakl_m01_s100_v30_long",
         path_key="lonakl", month=1, ssn=100, npsl=1)
    # Wide frequency spread
    emit("tanbel_m01_s100_v30_freqw",
         path_key="tanbel", month=1, ssn=100, freqs=FREQ_WIDE)

    with open(OUT.parent / "MANIFEST.tsv", "w", newline="\n") as f:
        f.write("name\tpath\tmonth\tssn\tcoeffs\tmethod\tnpsl\tfreqs\n")
        for name, kw in manifest:
            f.write("\t".join([
                name, kw["path_key"], str(kw["month"]), str(kw["ssn"]),
                kw.get("coeffs", "CCIR"), str(kw.get("method", 30)),
                str(kw.get("npsl", 0)),
                "wide" if kw.get("freqs") == FREQ_WIDE else "base",
            ]) + "\n")
    print(f"wrote {len(manifest)} decks to {OUT}")


if __name__ == "__main__":
    main()
