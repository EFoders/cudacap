def gcd_km(tlat, tlon, rlat, rlon):
    p1, p2 = math.radians(tlat), math.radians(rlat)
    dl = math.radians(rlon - tlon)
    c = (math.sin(p1) * math.sin(p2)
         + math.cos(p1) * math.cos(p2) * math.cos(dl))
    return 6370.0 * math.acos(max(-1.0, min(1.0, c)))


def signed(path_key):
    tx, tlat, tns, tlon, tew, rx, rlat, rns, rlon, rew = PATHS[path_key]
    return (tlat * (-1 if tns == "S" else 1), tlon * (-1 if tew == "W" else 1),
            rlat * (-1 if rns == "S" else 1), rlon * (-1 if rew == "W" else 1))


def deck(path_key, month, ssn, method, npsl):
    tx, tlat, tns, tlon, tew, rx, rlat, rns, rlon, rew = PATHS[path_key]
    sl = "L" if npsl else "S"
    lines = [
        "COMMENT   generated by tools/oracle/icepac/gen_icepac_decks.py",
        "LINEMAX      55       number of lines-per-page",
        "COEFFS    URSI",
        "TIME          1   24    1    1",
        f"MONTH      1994{month:5.2f}",
        f"SUNSPOT   {ssn:4.0f}.",
        f"LABEL     {tx:<20.20s}{rx:<20.20s}",
        (f"CIRCUIT   {tlat:5.2f}{tns}{tlon:9.2f}{tew}{rlat:9.2f}{rns}"
         f"{rlon:9.2f}{rew}  {sl} {npsl:5d}"),
        "SYSTEM       1. 145. 0.10  90. 73.0 3.00 0.10",
        "FPROB      1.00 1.00 1.00 0.70",
        "ANTENNA       1    1    2   30    10.000[samples/sample.00    ]"
        " 90.0  500.0000",
        "ANTENNA       2    2    2   30     0.000[samples/sample.00    ]"
        "270.0   20.0000",
        f"FREQUENCY {FREQ_BASE}",
        f"METHOD    {method:5d}    0",
        "EXECUTE",
        "QUIT",
    ]
    return "\n".join(line.rstrip() for line in lines) + "\n"


def name_of(path_key, month, ssn, method, npsl):
    return (f"{path_key}_m{month:02d}_s{ssn}_v{method}"
            f"{'_long' if npsl else ''}_ice")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for pk, month, ssn, method, npsl, what in CASES:
        name = name_of(pk, month, ssn, method, npsl)
        (OUT / f"{name}.dat").write_text(deck(pk, month, ssn, method, npsl),
                                         newline="\n")
        km = gcd_km(*signed(pk))
        if npsl:
            km = 2 * math.pi * 6370.0 - km
        rows.append((name, pk, month, ssn, method, npsl, f"{km:.0f}", what))
    with open(OUT / "MANIFEST.tsv", "w", newline="\n") as f:
        f.write("name\tpath\tmonth\tssn\tmethod\tnpsl\tkm\tcovers\n")
        for r in rows:
            f.write("\t".join(str(x) for x in r) + "\n")
    print(f"wrote {len(rows)} decks to {OUT}")
    print(" ".join(r[0] for r in rows))


if __name__ == "__main__":
    main()
