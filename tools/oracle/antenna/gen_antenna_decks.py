def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.dat"):
        old.unlink()
    rows = []
    for name, (kw, what) in DECKS.items():
        (OUT / f"{name}.dat").write_text(deck(**kw), newline="\n")
        ends = []
        for end in ("tx", "rx"):
            a = kw[end]
            ends.append(f"{a['file'].split('/')[-1]}@{a['beam']:g}"
                        f"[{a.get('fmin', 2)}..{a.get('fmax', 30)}]")
        rows.append((name, kw["path_key"], str(kw["month"]), str(kw["ssn"]),
                     kw.get("coeffs", "CCIR"), str(kw.get("method", 30)),
                     str(kw.get("npsl", 0)), ends[0], ends[1], what))
    with open(OUT / "MANIFEST.tsv", "w", newline="\n") as f:
        f.write("name\tpath\tmonth\tssn\tcoeffs\tmethod\tnpsl\ttx\trx\t"
                "covers\n")
        for r in rows:
            f.write("\t".join(r) + "\n")
    print(f"wrote {len(rows)} decks to {OUT}")


if __name__ == "__main__":
    main()
