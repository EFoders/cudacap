"""Stage B (PyTorch, batched) two-variable Fourier evaluator — NOISY.

NOISY is not a noise routine.  It is a general purpose evaluator of a Fourier
series in latitude and longitude over a stored coefficient map, and VOACAP
uses it for three unrelated things: the six 4-hour atmospheric-noise blocks
(KJ=1..6), a land-mass map (KJ=7), and the F2 height-of-max / semithickness
ratio TIMVAR wants (KJ=8).  Only the series LIMITS depend on KJ -- 15x10 for
KJ=8, 29x15 for everything else -- so the batched entry point takes the
coefficient slice, the two normalising constants and the limits as ARGUMENTS
rather than reaching into an IonoState.  Callers with a different overlay
(the Fortran aliases COMMON /TWO/ two ways; see stage_a/noisy.py) hand in
whatever slice they mean.

THE LOOP BOUNDS ARE TABLE CONSTANTS, NOT DATA.  LM and LN come from a two-way
branch on KJ, and KJ is a Python-level choice of which map to evaluate, not a
per-lane quantity.  So both loops stay Python loops and every lane runs the
same number of iterations -- no masking, no lockstep, nothing to select.  The
batching is purely over the trailing lane axis.

The two recurrences are the reason this cannot be a matmul.  Neither the
longitude harmonics SX(K)=sin(K*Q) nor the latitude ones are computed from
SIN directly; both are generated by an angle-addition recurrence off a single
SIN/COS pair, so their rounding is path-dependent and the series has to be
accumulated in the Fortran's order to keep the bits.  ``r = r + sx[k]*p[j,k]``
one term at a time, sequentially, is that order.  A dot product or a cumsum
would be free to reassociate and would drift -- and 435 terms of drift is
exactly where a Fourier map is most sensitive, because the high harmonics are
small differences of larger ones.

``p`` is indexed as ``p[j, k]`` with an OPTIONAL trailing lane axis, so a map
shared by the whole grid (the usual case -- REDMAP depends only on month and
SSN) can be passed as a plain (29, 16) tensor and costs no per-lane storage,
while a batch that genuinely varies per lane passes (29, 16, N).  Both fall
out of ordinary broadcasting; there is no separate code path.

float32.  SIN and COS are the only libm calls, and they enter once each per
axis -- but the recurrence then multiplies their error through 29 harmonics
and the series sums 435 terms of it, so this carries the
[[f32-libm-noise]] floor with real amplification.  Measured against the
oracle through ANOIS1: see tests/stage_b/test_anois1.py.
"""

import torch

from voacap_gpu.stage_b.profile import _k

_F32 = torch.float32

# Bound once at module level so a test can substitute Stage A's gfortran-
# matched SIN/COS and check what is left.  Nothing is: with sin32/cos32 in
# place of torch's, this reproduces stage_a/noisy.py BIT FOR BIT on both
# devices, which is what says the 435-term accumulation order is faithful and
# the whole residual is the libm pair.  See tests/stage_b/test_anois1.py.
_sin = torch.sin
_cos = torch.cos

# NOISY's own literals.  .0087266466 is D2R/2 (the longitude HALF angle) and
# .01745329252 is a D2R that does NOT match constants.D2R -- note the trailing
# 2.  Both are transcribed from noisy.for rather than derived, deliberately.
_LON_HALF = 0.0087266466
_LAT_D2R = 0.01745329252

# (LM, LN) per KJ: the IF(KJ-8) branch at label 100/105.
LIMITS_KJ8 = (15, 10)
LIMITS_DEFAULT = (29, 15)


def limits_for_kj(kj: int):
    """(LM, LN) for a map index, i.e. the Fortran's IF(KJ-8) 105,100,105."""
    return LIMITS_KJ8 if kj == 8 else LIMITS_DEFAULT


def noisy_batch(p, alf, bet, xla, ceg, lm=29, ln=15):
    """Batched NOISY.

    p:   coefficient map, ``p[j, k]`` for Fortran P(J+1, K+1, KJ).  Shape
         (29, 16) for a map shared by every lane, or (29, 16, N) / (29, 16, 1)
         for one that varies.  Only rows 0..lm-1 and columns 0..ln-1 are read,
         plus column 15 -- which is the CONSTANT term and is always column 16
         in Fortran terms even when LN is 10, so it is not ``p[j, ln]``.
    alf/bet: ABP(1,KJ), ABP(2,KJ), the linear normalisation.  Scalar tensor or
         (N,).
    xla: geographic latitude, degrees, + north.  (N,)
    ceg: geographic EAST longitude, degrees, 0..360.  (N,)
    lm/ln: series limits from ``limits_for_kj``.  Python ints -- these come
         from a fixed table and must not vary per lane.

    Returns ANOS, broadcast to the lane shape.
    """
    if not (1 <= ln <= 15 and 1 <= lm <= 29):
        raise ValueError(f"NOISY limits out of range: LM={lm}, LN={ln}")

    zero = _k(0.0, ceg)

    # ---- 110: longitude half-angle, and sin(K*Q) by angle addition --------
    q = _k(_LON_HALF, ceg) * ceg
    c1 = _cos(q)
    s1 = _sin(q)
    sx = [None] * (ln + 1)              # 1-based, mirroring SX(15)
    sx[1] = s1
    cx = c1
    for k in range(2, ln + 1):          # DO 115
        tx = sx[k - 1]
        sx[k] = tx * c1 + cx * s1
        cx = cx * c1 - tx * s1

    # ---- DO 125: the longitude series, one ZZ per latitude harmonic -------
    zz = [None] * (lm + 1)              # 1-based, mirroring ZZ(29)
    for j in range(1, lm + 1):
        r = zero
        for k in range(1, ln + 1):      # DO 120 -- sequential on purpose
            r = r + sx[k] * p[j - 1, k - 1]
        zz[j] = r + p[j - 1, 15]        # 125: + P(J,16,KJ)

    # ---- DO 130: the latitude series ---------------------------------------
    # The Fortran reuses SX(1) as the running sin(K*Q) here rather than
    # keeping the array; that is a scalar carry, not the longitude array, so
    # it gets its own name.
    q = _k(_LAT_D2R, xla) * (xla + _k(90.0, xla))
    s1 = _sin(q)
    c1 = _cos(q)
    sk = s1
    cx = c1
    r = zero
    for k in range(1, lm + 1):
        r = r + sk * zz[k]
        ss = sk * c1 + cx * s1
        cx = cx * c1 - sk * s1
        sk = ss

    # final value -- note the LINEAR normalisation in Q, not a series term
    return r + alf + bet * q
